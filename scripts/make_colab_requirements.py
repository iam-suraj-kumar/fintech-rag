"""Write requirements-colab.txt: requirements.txt without torch and the CUDA stack.

Google Colab ships a working torch (which docling needs); the pinned torch, torchvision,
triton and nvidia-* wheels in requirements.txt would download gigabytes and replace it.

    uv run python scripts/make_colab_requirements.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = re.compile(r"^(torch|torchvision|triton|nvidia-[a-z0-9-]+)==")

lines = (ROOT / "requirements.txt").read_text().splitlines()
kept, skipped, drop_comments = [], [], False
for line in lines:
    if line.startswith("-e "):
        continue  # the project itself: notebooks import it from the cloned repo instead
    if SKIP.match(line):
        skipped.append(line.split("==")[0])
        drop_comments = True  # also drop the "# via ..." lines that follow it
        continue
    if drop_comments and line.startswith(" "):
        continue
    drop_comments = False
    kept.append(line)
header = ["# Generated by scripts/make_colab_requirements.py from requirements.txt.",
          "# Same pins minus torch/torchvision/triton/nvidia-* (Colab already has torch)",
          "# and minus \"-e .\" (the notebooks import the cloned repo directly)."]
(ROOT / "requirements-colab.txt").write_text("\n".join(header + kept) + "\n")
print(f"wrote requirements-colab.txt ({len(skipped)} packages left to Colab: {', '.join(sorted(set(skipped)))})")
